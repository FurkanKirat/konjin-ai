#!/usr/bin/env python3
"""Held-out exact-match eval for the boilerplate model (needs minigpt.py in the same folder).

    python bp_eval.py --load models\\bp1.pt --dir bp\\test_names
    python bp_eval.py --load models\\bp1.pt --dir bp\\test_long --n 100 --show 3

For every .cs file in --dir: the text up to and including "// out:\\n" is the prompt, the rest is the
expected output. The model generates greedily until EOF; it is correct only if the bytes match exactly
(trailing whitespace ignored).
"""
import argparse
import glob
import os
import sys

OUT_MARK = "// out:\n"


def split_example(text):
    i = text.index(OUT_MARK) + len(OUT_MARK)
    task = text.split("\n", 1)[0].replace("// task:", "").strip()
    return task, text[:i], text[i:]


def first_diff(got, want):
    g, w = got.split("\n"), want.split("\n")
    for k in range(max(len(g), len(w))):
        a = g[k] if k < len(g) else "<missing>"
        b = w[k] if k < len(w) else "<missing>"
        if a != b:
            return k + 1, a, b
    return 0, "", ""


def evaluate(gen, files, n, show):
    """gen(prompt_bytes) -> generated bytes. Returns {task: [hits, total]}."""
    per, fails = {}, []
    for path in files[:n]:
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        task, prompt, want = split_example(text)
        got = gen(prompt.encode("utf-8")).decode("utf-8", errors="replace")
        ok = got.rstrip() == want.rstrip()
        h = per.setdefault(task, [0, 0])
        h[0] += int(ok)
        h[1] += 1
        if not ok:
            fails.append((os.path.basename(path), task, got, want))
    total = sum(v[1] for v in per.values())
    hits = sum(v[0] for v in per.values())
    print(f"exact match: {hits}/{total} = %{100 * hits / max(total, 1):.1f}")
    for t in sorted(per):
        print(f"  {t:12s} {per[t][0]}/{per[t][1]}  %{100 * per[t][0] / per[t][1]:.1f}")
    for name, task, got, want in fails[:show]:
        line, a, b = first_diff(got, want)
        print("-" * 60)
        print(f"{name} [{task}] first difference at line {line}:")
        print("  model:", a.strip())
        print("  real :", b.strip())
    return per


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--load", required=True)
    ap.add_argument("--dir", required=True)
    ap.add_argument("--n", type=int, default=200, help="max files to test")
    ap.add_argument("--show", type=int, default=3, help="how many failures to print")
    a = ap.parse_args()
    files = sorted(glob.glob(os.path.join(a.dir, "*.cs")))
    if not files:
        raise SystemExit(f"No .cs files in {a.dir}")
    sys.path[:0] = [os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), _d) for _d in ("model", "datagen", "eval")]
    import torch
    import minigpt as mg
    device = "cuda" if torch.cuda.is_available() else "cpu"
    ck = torch.load(a.load, map_location=device, weights_only=True)
    model = mg.build(ck["cfg"], device)
    model.load_state_dict(ck["model"])
    vocab = ck["vocab"]
    print(f"model: {a.load}  files: {min(a.n, len(files))} from {a.dir}")
    evaluate(lambda p: mg.sample_bytes(model, vocab, p, 900, 0.0, device), files, a.n, a.show)


if __name__ == "__main__":
    main()
